#!/usr/bin/env python3
"""Build the GT Mesh study's videos: pick N clips at random and keep only GT Video | GT Mesh.

The source clips are 5 square panels side by side (GT Video, GT Mesh, A, B, C).
This keeps the first two panels, re-encodes them as web-friendly H.264, and writes
videos.js (the list the site shows) and selected_videos.txt (which source clips were used).

Each clip has its sentence as a subtitle along the bottom, which runs past the GT Mesh
panel for long sentences and would be cut. So clips listed in subtitles.tsv keep only
their top CROP_HEIGHT rows, and the page shows the sentence above the video instead.

    python3 mesh/make_mesh_videos.py ~/Downloads/compare_openasl_generation_anonymous

The pick is seeded, so running it again gives the same 50 clips. Use --seed to draw a
different set and --force to re-encode clips that already exist.
"""

import argparse
import json
import random
import shutil
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
VIDEO_DIR = HERE / "videos"
OUT = HERE / "videos.js"
SELECTED = HERE / "selected_videos.txt"
SUBTITLES = HERE / "subtitles.tsv"
PANELS_KEPT = 2  # GT Video, GT Mesh
CROP_HEIGHT = 454  # the subtitle starts at row 456


def web_name(name):
    # ":" in the timestamps is not allowed on Windows and has to be escaped in URLs.
    return name.replace(":", "-")


def read_sentences():
    """subtitles.tsv: video file name, tab, sentence (lines starting with # are comments)."""
    if not SUBTITLES.exists():
        return {}
    out = {}
    for line in SUBTITLES.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            name, _, sentence = line.partition("\t")
            out[name.strip()] = sentence.strip()
    return out


def crop(src, dst, height):
    # Panels are square, so the source height is also the width of one panel.
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-i", str(src),
         "-vf", f"crop={PANELS_KEPT}*ih:{height}:0:0",
         "-an", "-c:v", "libx264", "-preset", "slow", "-crf", "20",
         "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(dst)],
        check=True,
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path, help="folder of 5-panel comparison videos")
    ap.add_argument("-n", type=int, default=50, help="how many clips to pick (default 50)")
    ap.add_argument("--seed", type=int, default=2026, help="random seed for the pick (default 2026)")
    ap.add_argument("--force", action="store_true", help="re-encode clips that already exist")
    args = ap.parse_args()

    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg is needed (brew install ffmpeg).")
    pool = sorted(p for p in args.source.glob("*.mp4") if not p.name.startswith("."))
    if len(pool) < args.n:
        sys.exit(f"Only {len(pool)} videos in {args.source}, fewer than {args.n}.")
    picked = sorted(random.Random(args.seed).sample(pool, args.n), key=lambda p: p.name)

    VIDEO_DIR.mkdir(exist_ok=True)
    keep = {web_name(p.name) for p in picked}
    for old in VIDEO_DIR.glob("*.mp4"):
        if old.name not in keep:
            old.unlink()
            print(f"  removed {old.name}")

    sentences = read_sentences()
    entries, total = [], 0
    for i, src in enumerate(picked, 1):
        dst = VIDEO_DIR / web_name(src.name)
        sentence = sentences.get(dst.name, "")
        if args.force or not dst.exists():
            print(f"  [{i}/{len(picked)}] {src.name}")
            crop(src, dst, CROP_HEIGHT if sentence else "ih")
        if not sentence:
            print(f"  warn  {dst.name}: no sentence in {SUBTITLES.name}; its subtitle is left in the video.")
        total += dst.stat().st_size
        entry = {"id": dst.name, "src": "videos/" + quote(dst.name), "panels": PANELS_KEPT}
        if sentence:
            entry["sentence"] = sentence
        entries.append(entry)

    body = ",\n".join("  " + json.dumps(e, ensure_ascii=False) for e in entries)
    OUT.write_text(
        "// Generated by make_mesh_videos.py. Re-run it to change the set of videos.\n"
        "window.STUDY_VIDEOS = [\n" + body + ",\n];\n",
        encoding="utf-8",
    )
    SELECTED.write_text(
        f"# {args.n} clips picked from {args.source.name}/ with seed {args.seed}\n"
        + "".join(p.name + "\n" for p in picked),
        encoding="utf-8",
    )
    print(f"\nWrote {OUT.name} with {len(entries)} videos, {total / 1024 / 1024:.1f} MB total.")


if __name__ == "__main__":
    main()
